"""
tests/test_pipeline.py

Round-trip tests for the two composed experimental pipelines in
src/pipeline.py:
  - Pipeline A: DNA-domain transform + AES-GCM
  - Pipeline B (control): AES-GCM only

Uses the project's fixed AES key (data/aes_key.bin, generated once via
os.urandom(32) and reused across all experiments — never regenerated by
this test) and the fixed reference DNA sequence
(data/reference_sequence.txt).
"""

import os
import random
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "src")))

from pipeline import (
    pipeline_a_dna_plus_classical,
    pipeline_b_classical_only,
    decrypt_pipeline_a,
    decrypt_pipeline_b,
)

DATA_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data"))
AES_KEY_PATH = os.path.join(DATA_DIR, "aes_key.bin")
REFERENCE_SEQUENCE_PATH = os.path.join(DATA_DIR, "reference_sequence.txt")


def _load_key() -> bytes:
    # Fixed key generated once and reused across all experiments; never
    # regenerated here (this test only creates it if it is somehow
    # missing, so the suite is still runnable from a clean checkout).
    if not os.path.exists(AES_KEY_PATH):
        with open(AES_KEY_PATH, "wb") as f:
            f.write(os.urandom(32))
    with open(AES_KEY_PATH, "rb") as f:
        return f.read()


def _load_reference_sequence() -> str:
    with open(REFERENCE_SEQUENCE_PATH) as f:
        return f.read().strip()


KEY = _load_key()
REFERENCE_SEQUENCE = _load_reference_sequence()


def _random_byte_strings(n=20, min_len=10, max_len=200_000, seed=42):
    rng = random.Random(seed)
    for _ in range(n):
        length = rng.randint(min_len, max_len)
        yield bytes(rng.getrandbits(8) for _ in range(length))


class TestPipelineARoundTrip:
    def test_round_trip_random_lengths(self):
        for data in _random_byte_strings():
            stages = pipeline_a_dna_plus_classical(data, KEY, REFERENCE_SEQUENCE)
            recovered = decrypt_pipeline_a(stages, KEY, REFERENCE_SEQUENCE)
            assert recovered == data

    def test_stage_keys_present(self):
        stages = pipeline_a_dna_plus_classical(b"some sample data", KEY, REFERENCE_SEQUENCE)
        assert set(stages.keys()) == {"input", "post_dna", "post_classical"}


class TestPipelineBRoundTrip:
    def test_round_trip_random_lengths(self):
        for data in _random_byte_strings():
            stages = pipeline_b_classical_only(data, KEY)
            recovered = decrypt_pipeline_b(stages, KEY)
            assert recovered == data

    def test_stage_keys_present(self):
        stages = pipeline_b_classical_only(b"some sample data", KEY)
        assert set(stages.keys()) == {"input", "post_classical"}
